package strata.foundation.core.event;

import java.util.Collection;

public
interface IEventListener<E>
{
    default void
    onStart() throws StartException {}

    default void
    onStop() {}

    void
    onEvents(Collection<E> events);

    void
    onException(Exception exception);
}

